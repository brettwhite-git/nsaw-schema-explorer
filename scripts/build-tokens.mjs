// tokens.json -> styles/tokens.generated.css
// Dark (the default theme) goes on :root, light under [data-theme="light"].
// Code never hand-copies a token value: change tokens.json and run `npm run tokens`.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const kebab = (k) => k.replace(/([a-z0-9])([A-Z0-9])/g, '$1-$2').toLowerCase();

function colorVars(set) {
  return Object.entries(set).map(([k, v]) => `  --${kebab(k)}: ${v.value};`);
}

export function buildTokensCss(t) {
  const tex = t.paperTexture;
  const shared = [
    `  --serif: ${t.font.serif};`,
    `  --mono: ${t.font.mono};`,
    ...Object.entries(t.line.weights).map(([k, v]) => `  --w-${kebab(k)}: ${v}px;`),
    `  --thread-w: ${t.line.thread.stroke}px;`,
    `  --thread-dash: ${t.line.thread.dash}px ${t.line.thread.gap}px;`,
    `  --thread-opacity: ${t.line.thread.opacity};`,
    `  --thread-focus-opacity: ${t.line.thread.focusOpacity};`,
    `  --ease-draw: ${t.motion.easing.draw};`,
    `  --ease-text: ${t.motion.easing.text};`,
    `  --dur-hover: ${t.motion.dur.hover}ms;`,
    `  --dur-text: ${t.motion.dur.textFade}ms;`,
    `  --dur-label: ${t.motion.dur.labelWrite}ms;`,
    `  --pad-sheet: ${t.spacing.sheetPadding}px;`,
    `  --pad-sheet-narrow: ${t.spacing.sheetPaddingNarrow}px;`,
    `  --gap-block: ${t.spacing.blockGap}px;`,
    `  --hit-control: ${t.hit.minControlPx}px;`,
    `  --tile: ${tex.tilePx}px;`,
  ];
  const dark = [...colorVars(t.colorsDark), `  --tex: url(${tex.dark});`, `  --blend: ${tex.blend.dark};`, '  color-scheme: dark;'];
  const light = [...colorVars(t.colors), `  --tex: url(${tex.light});`, `  --blend: ${tex.blend.light};`, '  color-scheme: light;'];
  return [
    '/* GENERATED by scripts/build-tokens.mjs from tokens.json. Do not edit; run `npm run tokens`. */',
    ':root {', ...shared, ...dark, '}',
    ':root[data-theme="light"] {', ...light, '}',
    ':root[data-theme="dark"] {', ...dark, '}',
    '',
  ].join('\n');
}

export function writeTokens() {
  const t = JSON.parse(fs.readFileSync(path.join(root, 'tokens.json'), 'utf8'));
  const css = buildTokensCss(t);
  fs.mkdirSync(path.join(root, 'styles'), { recursive: true });
  fs.writeFileSync(path.join(root, 'styles/tokens.generated.css'), css);
  return css;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const css = writeTokens();
  console.log(`styles/tokens.generated.css: ${css.split('\n').length} lines`);
}
