// The matrix page's inspector (the shared <Inspector>): two picked rows (a pair to compare), one picked row, one
// picked dimension column, the hovered row, or a short guide. Detail sections render only when they have data.
import { Link } from '../../router';
import { areaPath, comparePath, matrixPath, tablePath } from '../../routes';
import { Inspector, InspectorSection, type InspectorAction } from '../Inspector';
import { inspectArea, inspectDimension, inspectPair } from '../inspector/builders';
import { areaGrainSentence, areaSummary, compare, dimensionReach, factsInSameAreas, plural, prettyTable, reach, reportFoldersReading, shortTable, unsecuredName, unslug, type AreaFact, type ColumnModel, type CoreModel } from '../../../explorer/data';
import { matrixLayout, ordinal, type Sel } from './shared';

export interface SidePanelProps {
  m: CoreModel;
  cm: ColumnModel | null;
  sel: Sel;
  hoverRow: number | null;
  onSel: (s: Sel) => void;
}

/**
 * The matrix page's inspector. In order of precedence: two picked rows (a pair), one picked row, one picked
 * dimension column, the hovered row, or a short guide. Same <Inspector> as every page; the matrix's own lists
 * (facts and their grain, reach by functional area, report folders, facts in the same areas) are its details.
 */
export function SidePanel({ m, cm, sel, hoverRow, onSel }: SidePanelProps) {
  const pickDim = (c: number) => {
    const { bandOf } = matrixLayout(m);
    const open = new Set(sel.open);
    if (bandOf[c] >= 0) open.add(bandOf[c]);
    onSel({ a: null, b: null, dim: c, open });
  };
  const clear = () => onSel({ ...sel, a: null, b: null, dim: null });
  if (sel.a !== null && sel.b !== null) {
    const saA = m.bus.rows[sel.a], saB = m.bus.rows[sel.b];
    return <Inspector {...inspectPair(m, saA, saB)} onClose={clear} closeLabel="Clear both rows"><PairDetails m={m} a={saA} b={saB} pickDim={pickDim} /></Inspector>;
  }
  if (sel.a !== null) {
    const sa = m.bus.rows[sel.a];
    return (
      <Inspector {...inspectArea(m, sa)} onClose={clear} closeLabel="Clear the row">
        <RowDetails m={m} sa={sa} />
        <p className="mx-hint">Click a second row to compare the two areas.</p>
      </Inspector>
    );
  }
  if (sel.dim !== null) {
    const t = m.bus.columns[sel.dim];
    const p = inspectDimension(m, t);
    return (
      <Inspector {...p} eyebrow={`dimension, ${ordinal(sel.dim + 1)} most shared of ${m.bus.columns.length}`}
        lead={m.bus.columnDerived[sel.dim] ? 'Generated by NSAW.' : p.lead} onClose={clear} closeLabel="Clear the column">
        <DimDetails m={m} cm={cm} c={sel.dim} />
      </Inspector>
    );
  }
  if (hoverRow !== null) {
    const sa = m.bus.rows[hoverRow];
    return <Inspector {...inspectArea(m, sa)}><RowDetails m={m} sa={sa} /><p className="mx-hint">Click the row to pick it.</p></Inspector>;
  }
  return <GuidePanel m={m} pickDim={pickDim} />;
}

function DimList({ m, cols, hot, pickDim }: { m: CoreModel; cols: number[]; hot?: boolean; pickDim: (c: number) => void }) {
  return (
    <ul className={`mx-dl${hot ? ' hot' : ''}`}>
      {cols.map((c) => (
        <li key={c}>
          <button type="button" onClick={() => pickDim(c)} title={m.tables[m.bus.columns[c]].name}>
            <span className="nm">{prettyTable(m, m.tables[m.bus.columns[c]].name)}</span>
            <span className="n">{reach(m, c)}</span>
          </button>
        </li>
      ))}
    </ul>
  );
}

// ------------------------------------------------------------------ guide
function GuidePanel({ m, pickDim }: { m: CoreModel; pickDim: (c: number) => void }) {
  const top = [0, 1, 2, 3, 4, 5].filter((c) => c < m.bus.columns.length);
  const { bands } = matrixLayout(m);
  const so = unslug(m, 'sales-order'), ci = unslug(m, 'customer-invoice');
  const emp = m.tableByName.get('DW_NS_EMPLOYEE_D');
  const actions: InspectorAction[] = [];
  if (so !== undefined) actions.push({ label: m.subjectAreas[so].label, sub: 'one subject area: its facts and the tables they relate to', to: areaPath(m.subjectAreas[so].slug) });
  if (so !== undefined && ci !== undefined) actions.push({ label: `${m.subjectAreas[so].label} and ${m.subjectAreas[ci].label}`, sub: 'compare two Order to Cash areas', to: comparePath(m.subjectAreas[so].slug, m.subjectAreas[ci].slug) });
  if (emp !== undefined && m.tables[emp].col >= 0) actions.push({ label: prettyTable(m, m.tables[emp].name), sub: 'one dimension, many report folders', to: matrixPath({ dim: m.tables[emp].name }) });
  return (
    <Inspector kind="area" eyebrow="reading the matrix" title="Rows, columns and marks"
      visual={(
        <ol className="mx-howto">
          <li>Hover a row to see its facts and the grain of each.</li>
          <li>Click two rows to compare the dimensions they list.</li>
          <li>Click a column name to see where a dimension reaches and which report folders read from it.</li>
        </ol>
      )}
      actions={actions}>
      <InspectorSection title="Widest reach" count="areas">
        <DimList m={m} cols={top} pickDim={pickDim} />
        {top.length > 0 && (
          <p className="mx-note">
            {top.length} dimensions reach {reach(m, top[top.length - 1])} or more of the {m.subjectAreas.length} subject areas.
            {bands.length > 0 && ` ${bands[bands.length - 1].cols.length} reach ${bands[bands.length - 1].hi} or fewer.`}
          </p>
        )}
      </InspectorSection>
    </Inspector>
  );
}

// ------------------------------------------------------------------ one row
interface FactGroup { main: AreaFact; sec: AreaFact | null }
function groupFacts(facts: AreaFact[]): FactGroup[] {
  const by = new Map<string, FactGroup>();
  for (const f of facts) {
    const k = unsecuredName(f.name);
    const g = by.get(k);
    if (!g) by.set(k, { main: f, sec: null });
    else if (!g.sec && g.main.secured !== f.secured) { if (f.secured) g.sec = f; else { g.sec = g.main; g.main = f; } }
    else by.set(`${k}#${f.table}`, { main: f, sec: null });
  }
  return [...by.values()];
}

export function FactBlock({ f, sec, area }: { f: AreaFact; sec?: AreaFact | null; area?: string }) {
  return (
    <div className="mx-fact">
      <div className="f-name">
        <Link className="mono" to={tablePath(f.name, area)}>{f.name}</Link>
        {f.secured && <span className="badge">secured</span>}
      </div>
      {f.grain && <p className="f-grain">{f.grain}</p>}
      {f.key.length > 0 && (
        <p className="f-key">
          <span>key</span>
          {f.key.map((k, i) => (
            <span key={k}>{i > 0 && <span className="plus">+</span>}<span className="ktag">{k}</span></span>
          ))}
        </p>
      )}
      {sec && (
        <div className="f-sec">
          <Link className="mono" to={tablePath(sec.name, area)}>{sec.name}</Link>
          <span className="badge">secured</span>
        </div>
      )}
    </div>
  );
}

function RowDetails({ m, sa }: { m: CoreModel; sa: number }) {
  const s = m.subjectAreas[sa];
  const area = areaSummary(m, null, sa);
  const groups = groupFacts(area.facts);
  const note = areaGrainSentence(m, sa);
  if (!groups.length) return null;
  return (
    <InspectorSection title="Its facts and their grain" count={groups.length}>
      {note && <p className="mx-note">{note}</p>}
      {groups.map((g) => <FactBlock key={g.main.table} f={g.main} sec={g.sec} area={s.slug} />)}
    </InspectorSection>
  );
}

// ------------------------------------------------------------------ two rows
function PairDetails({ m, a, b, pickDim }: { m: CoreModel; a: number; b: number; pickDim: (c: number) => void }) {
  const A = m.subjectAreas[a], B = m.subjectAreas[b];
  const c = compare(m, a, b);
  return (
    <>
      {c.onlyA.length > 0 && <InspectorSection title={`Only in ${A.label}`} count="reach"><DimList m={m} cols={c.onlyA} hot pickDim={pickDim} /></InspectorSection>}
      {c.onlyB.length > 0 && <InspectorSection title={`Only in ${B.label}`} count="reach"><DimList m={m} cols={c.onlyB} hot pickDim={pickDim} /></InspectorSection>}
      {c.both.length > 0 && (
        <details className="mx-shared">
          <summary>{plural(c.both.length, 'dimension')} listed under both</summary>
          <p className="mx-quiet">{c.both.map((x) => prettyTable(m, m.tables[m.bus.columns[x]].name)).join(', ')}</p>
        </details>
      )}
    </>
  );
}

// ------------------------------------------------------------------ one dimension
const FOLDERS_SHOWN = 14, FACTS_SHOWN = 10;

function DimDetails({ m, cm, c }: { m: CoreModel; cm: ColumnModel | null; c: number }) {
  const t = m.bus.columns[c];
  const name = m.tables[t].name;
  const perFa = dimensionReach(m, c).filter((x) => x.total > 0);
  const folders = cm ? reportFoldersReading(m, cm, t) : [];
  const facts = factsInSameAreas(m, c);
  const maxW = Math.max(1, ...facts.map((x) => x.areas));
  return (
    <>
      {perFa.length > 0 && (
        <InspectorSection title="Reach by functional area">
          <ul className="mx-bars">
            {perFa.map((p) => (
              <li key={p.fa}>
                <span className="nm">{p.name}</span>
                <span className="m" aria-hidden="true"><i style={{ width: `${(p.has / p.total) * 100}%` }} /></span>
                <span className="n">{p.has} of {p.total}</span>
              </li>
            ))}
          </ul>
        </InspectorSection>
      )}

      {!cm && <p className="mx-note">Loading report folders…</p>}
      {folders.length > 0 && (
        <InspectorSection title="Report folders that read from it" count="areas">
          <p className="mx-roles">
            {folders.slice(0, FOLDERS_SHOWN).map((f) => <span key={f.name}><em>{f.name}</em> <span className="n">{f.areas}</span></span>)}
          </p>
          <p className="mx-note">
            Report folders with a column that Oracle’s lineage maps to a column of {shortTable(name)}
            {folders.length > FOLDERS_SHOWN ? `, ${folders.length} in all.` : '.'}
          </p>
        </InspectorSection>
      )}

      {facts.length > 0 && (
        <InspectorSection title="Facts in the same subject areas" count="areas">
          <p className="mx-note">Oracle’s lineage lists {plural(facts.length, 'fact table')} in the subject areas that list this dimension.</p>
          <ul className="mx-bars fx">
            {facts.slice(0, FACTS_SHOWN).map((x) => (
              <li key={x.table}>
                <Link className="mono nm" to={tablePath(m.tables[x.table].name)} title={m.tables[x.table].name}>{shortTable(m.tables[x.table].name)}</Link>
                <span className="m" aria-hidden="true"><i style={{ width: `${(x.areas / maxW) * 100}%` }} /></span>
                <span className="n">{x.areas}</span>
              </li>
            ))}
          </ul>
          {facts.length > FACTS_SHOWN && <p className="mx-note">And {facts.length - FACTS_SHOWN} more on the table page.</p>}
        </InspectorSection>
      )}
    </>
  );
}
